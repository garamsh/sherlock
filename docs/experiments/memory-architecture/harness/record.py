"""Writes the record's five result tables from the committed runs.

Each table under §The results is an excerpt of one file in `results/`: some of
its rows, some of its columns, at the record's own precision. The record used to
carry those excerpts by hand and a register checked each cell against the file
behind it. They are now generated between markers, so a cell cannot disagree
with the run that produced it and there is nothing left to check.

`python3 harness/record.py` rewrites them from the committed results and
measures nothing; every runner calls `write` after writing its own file, so a
run leaves the record consistent with it.

Which rows an excerpt shows, what it calls them, what it emphasises and how many
decimals it prints are the record's editorial choices, and they live in TABLES
below because a generated table cannot hold them.
"""
