def rows_of(name):
    """Rows of the one table in `results/<name>.md`, as a list of dicts."""
    lines = [ln for ln in open(os.path.join(RESULTS, f"{name}.md"))
             if ln.lstrip().startswith("|")]
    header, rows = None, []
    for line in lines:
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if set(line.strip()) <= set("|-: "):
            continue
        if header is None:
            header = cells
        elif cells != header:
            rows.append(dict(zip(header, cells)))
    return rows


def half_up(value, digits):
    """Round half away from zero, the direction a reader assumes."""
    factor = 10 ** digits
    return math.floor(abs(value) * factor + 0.5) / factor * (1 if value >= 0 else -1)


def figure(value, column):
    """One cell at the precision the record prints that column to."""
    decimals, grouped = FORMATS[column]
    rounded = half_up(float(str(value).replace(",", "")), decimals)
    return f"{rounded:{',' if grouped else ''}.{decimals}f}"


def render(spec):
    """One excerpt table, from the result file it names."""
    source = rows_of(spec["file"])
    if "select" in spec:
        key, value = spec["select"]
        source = [r for r in source if float(r[key]) == value]
    by_arch = {r["arch"]: r for r in source}
    columns = list(spec["columns"])
    out = ["| arch | " + " | ".join(columns) + " |",
           "|" + "---|" * (len(columns) + 1)]
    for arch, label, bold in spec["rows"]:
        names = arch if isinstance(arch, tuple) else (arch,)
        cells = []
        for column in columns:
            values = {figure(by_arch[n][spec["columns"][column]], column)
                      for n in names}
            if len(values) != 1:
                raise SystemExit(
                    f"{label} merges rows that disagree on {column}: {sorted(values)}")
            cells.append(values.pop())
        emphasised = columns if bold == "all" else bold
        cells = [f"**{c}**" if columns[i] in emphasised else c
                 for i, c in enumerate(cells)]
        shown = f"**{label}**" if bold == "all" or "arch" in bold else label
        out.append("| " + shown + " | " + " | ".join(cells) + " |")
    return "\n".join(out)


def replace(record, name, table):
    """Put one generated table between the markers that name it."""
    begin = record.find(BEGIN.format(name))
    if begin < 0:
        raise SystemExit(f"the record carries no generated block named {name}")
    end = record.find(END, begin)
    if end < 0:
        raise SystemExit(f"the {name} block has no end marker")
    return (record[:begin + len(BEGIN.format(name))] + "\n\n" + table + "\n\n"
            + record[end:])


def write():
    """Rewrite every generated table in the record from `results/`."""
    path = os.path.join(ROOT, "README.md")
    with open(path) as f:
        record = f.read()
    for name, spec in TABLES.items():
        record = replace(record, name, render(spec))
    with open(path, "w") as f:
        f.write(record)
    return path


