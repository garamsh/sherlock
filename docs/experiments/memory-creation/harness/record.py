"""Writes every result table in the record from the committed runs.

The record used to carry each cell by hand and the two registers beside it
checked every one against the file behind it. They are generated now, between
markers named for each table, so a cell cannot disagree with the run that
produced it.

`python3 harness/record.py` rewrites them all and measures nothing. One module
because there is one record: rounds 4 and 5 are two measurements written into
one document, and what puts a table into that document is the same either way.

What each table shows, what it calls its rows, how it groups them and what it
emphasises are the record's editorial choices, and they live here because a
generated table cannot hold them. The prose around the tables still states
figures, and each round's `claim_sources.py` still reads those against their
sources.
"""
from __future__ import annotations
import importlib.util
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
ROUND4_RESULTS = os.path.join(ROOT, "results_round4")
ROUND5_RESULTS = os.path.join(ROOT, "results_round5")

BEGIN = "<!-- generated by the harness; do not edit between the markers: {} -->"
END = "<!-- end generated -->"


def _load(round_dir, name):
    """One round's module, by path.

    Both rounds name a module `precision` and this file needs both, so an
    ordinary import cannot reach them; `round5/round4.py` loads round 4's
    `dataset` and `scoring` the same way.
    """
    path = os.path.join(HERE, round_dir, f"{name}.py")
    spec = importlib.util.spec_from_file_location(f"{round_dir}_{name}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


round4_precision = _load("round4", "precision")
round5_precision = _load("round5", "precision")


def fixed(value, places):
    """One cell at the precision the record prints it to.

    Rounds half away from zero, which is the direction a reader assumes and the
    direction every committed figure in the record was written in; Python's own
    formatting rounds half to even and would move a cell sitting exactly on a
    half. The settle first keeps a value the arithmetic left just under a half
    on the side it belongs.
    """
    settled = round(abs(value), places + 6)
    factor = 10 ** places
    rounded = math.floor(settled * factor + 0.5) / factor
    return f"{-rounded if value < 0 else rounded:.{places}f}"


def thousands(n):
    return f"{int(n):,}"


