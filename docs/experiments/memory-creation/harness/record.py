def render_arms():
    """What each phrasing of the same corrections was judged to be."""
    arms = load("marker_following_seed7")["judgment"]["arms"]
    out = ["| arm | marker | phrasing | retired "
           "| mean cosine to the row it contradicts |",
           "|---|---|---|---|---|"]
    for tag, phrasing in ARMS:
        a = arms[tag]
        out.append(f"| {tag} | {'yes' if a['marker'] else 'no'} | {phrasing} | "
                   f"{a['retired']} — {fixed(a['rate'], 2)} | "
                   f"{fixed(a['mean_cosine'], 3)} |")
    return "\n".join(out)


def render_categories():
    """Every category under every arm, grouped as the record reads them."""
    cats = load("marker_following_seed7")["by_category"]
    out = ["| category | n | A | B | C | D |", "|---|---|---|---|---|---|"]
    for group, bold in CATEGORY_ROWS:
        names = sorted(cats) if group is None else group
        label = f"all {len(cats)}" if group is None else ", ".join(group)
        cells = []
        for key in ("n", "A", "B", "C", "D"):
            cell = str(sum(cats[c][key] for c in names))
            cells.append(f"**{cell}**" if key in bold else cell)
        out.append(f"| {label} | " + " | ".join(cells) + " |")
    return "\n".join(out)



