def load(name):
    with open(os.path.join(RESULTS, f"{name}.json")) as f:
        return json.load(f)


def sweep_row(seed, system):
    """One structure's scored row from the seed's falsification sweep."""
    for r in load(f"falsification_seed{seed}")["rows"]:
        if r["system"] == system:
            return r
    return None


def scored(system, seed):
    """The scored row for one structure at one seed, wherever it was written."""
    row = sweep_row(seed, system)
    if row is not None:
        return row
    path = os.path.join(RESULTS, f"{system}_seed{seed}.json")
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)["row"]


def fixed(value, places):
    """One cell at the precision the record prints it to.

    Rounds half away from zero, which is the direction a reader assumes and the
    direction every committed figure in the record was written in; Python's own
    formatting rounds half to even and would move a cell sitting exactly on a
    half. The settle first keeps a value the arithmetic left just under a half
    on the side it belongs.
    """
    settled = round(abs(value), places + 6)
    factor = 10 ** places
    rounded = math.floor(settled * factor + 0.5) / factor
    return f"{-rounded if value < 0 else rounded:.{places}f}"


def thousands(n):
    return f"{int(n):,}"


def render_probe_families():
    """How many probes each family carries, and what it scores."""
    kinds = load("falsification_seed7")["probe_kinds"]
    out = ["| family | probes | scores |", "|---|---|---|"]
    for family, scores in FAMILY_SCORES:
        out.append(f"| {family} | {kinds[family]} | {scores} |")
    return "\n".join(out)


def render_pair_families():
    """Each pair family's cosine distribution, at both dimensions."""
    at512, at1536 = load("separability"), load("separability_dims1536")
    out = ["| pair family | must supersede? | median (512) | IQR (512) "
           "| median (1536) | IQR (1536) |",
           "|---|---|---|---|---|---|"]
    for family, must in PAIR_FAMILIES:
        a, b = at512["families"][family], at1536["families"][family]
        out.append(f"| {family} | {must} | {fixed(a['median'], 3)} | "
                   f"{fixed(a['iqr'], 3)} | {fixed(b['median'], 3)} | "
                   f"{fixed(b['iqr'], 3)} |")
    return "\n".join(out)


def render_thresholds():
    """What each candidate threshold retires, at both dimensions."""
    at512, at1536 = load("separability"), load("separability_dims1536")
    out = ["| threshold | correct retirements (512) | wrong retirements (512) "
           "| correct (1536) | wrong (1536) |",
           "|---|---|---|---|---|"]
    for key, label in THRESHOLDS:
        a, b = at512[key], at1536[key]
        value = a.get("t", a.get("threshold"))
        out.append(f"| {label.format(fixed(value, 2))} | "
                   f"{a['correct_retirements']} | {a['wrong_retirements']} | "
                   f"{b['correct_retirements']} | {b['wrong_retirements']} |")
    return "\n".join(out)


def render_structures():
    """Every structure round 4 scored, ranked as the record ranks them."""
    out = ["| structure | what the decider is shown, and what it returns "
           "| latest-wins | control | coexist | net | net (s11) "
           "| control retired | items |",
           "|---|---|---|---|---|---|---|---|---|"]
    for _, label, shown, system, bold_label, bold in STRUCTURES:
        base = scored(system, 7)
        cells = []
        for name, key, places in STRUCTURE_COLUMNS:
            row = scored(system, 11) if name == "net (s11)" else base
            if row is None:
                cells.append("—")
                continue
            cell = str(row[key]) if places is None else fixed(row[key], places)
            cells.append(f"**{cell}**" if name in bold else cell)
        shown_label = f"**{label}**" if bold_label else label
        out.append(f"| {shown_label} | {shown} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def render_coexist_families():
    """What each key-addressed run preserved, per coexist family."""
    fam = {f["family"]: f for f in load("coexist_families_seed7")["families"]}
    out = ["| family | values | " + " | ".join(label for _, label in COEXIST_ARMS) + " |",
           "|---|---|---|---|---|"]
    for family in COEXIST_FAMILIES:
        f = fam[family]
        out.append(f"| {family} | {f['values']} | "
                   + " | ".join(str(f["preserved"][tag]) for tag, _ in COEXIST_ARMS)
                   + " |")
    return "\n".join(out)


def render_budgets():
    """What a probe budget buys on `net`, at family scores held fixed."""
    budget = {(c, x): h for c, x, h in precision.budget()}
    out = ["| corrected probes | coexist probes | 95% half-width on `net` |",
           "|---|---|---|"]
    for corrected, coexist in BUDGETS:
        out.append(f"| {corrected} | {coexist} | ±{fixed(budget[(corrected, coexist)], 3)} |")
    return "\n".join(out)


