"""Writes §Round 5's four tables in the record from the committed results.

The record used to carry these by hand and `claim_sources.py` checked every
cell against the file behind it. They are generated now, between markers named
for each, so a cell cannot disagree with the run that produced it.

`python3 harness/round5/record.py` rewrites them and measures nothing.

What each table shows, what it calls its rows and what it emphasises are the
record's editorial choices, and they live here because a generated table cannot
hold them. The prose around the tables still states figures, and
`claim_sources.py` still reads those against their sources.
"""
from __future__ import annotations
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
RESULTS = os.path.join(ROOT, "results_round5")

sys.path.insert(0, HERE)

import precision

BEGIN = "<!-- generated by the harness; do not edit between the markers: {} -->"
END = "<!-- end generated -->"

# The structures round 5 measured, in the order the record lists them, and what
# it calls each.
TAGS = {"B14": "B14-key-upsert-plural", "B17": "B17-key-upsert-question-key",
        "B3": "B3-decider-neighbors", "B9": "B9-decider-neighbors-wide"}
LABELS = {"B14": "B14 key-upsert, plural-aware",
          "B17": "B17 key-upsert, question-shaped key",
          "B3": "B3 decider-neighbours",
          "B9": "B9 decider-neighbours, wide"}
SEEDS = (7, 11)
COLUMNS = [("latest-wins", "latest_wins"), ("control", "control_survival"),
           ("coexist", "coexist_preserved"), ("net", "net")]

# The one cell the record sets in bold: the column round 5 separates.
POOLED_EMPHASIS = ("B14", "coexist_preserved")


def fixed(value, places):
    """One cell at the precision the record prints it to.

    Rounds half away from zero, which is the direction a reader assumes and the
    direction every committed figure in the record was written in; Python's own
    formatting rounds half to even and would move a cell sitting exactly on a
    half. The settle first keeps a value the arithmetic left just under a half
    — 0.9249999999999999 for 0.925 — on the side it belongs.
    """
    settled = round(abs(value), places + 6)
    factor = 10 ** places
    rounded = math.floor(settled * factor + 0.5) / factor
    return f"{-rounded if value < 0 else rounded:.{places}f}"


def rows():
    """{tag: {seed: row}} from the committed round-5 results."""
    out = {}
    for tag, system in TAGS.items():
        for seed in SEEDS:
            with open(os.path.join(RESULTS, f"{system}_seed{seed}.json")) as f:
                out.setdefault(tag, {})[seed] = json.load(f)["row"]
    return out


def pooled_scores():
    """{tag: pooled family scores}, the way precision.py pools them."""
    loaded = precision.load()
    return {tag: precision.pooled(loaded[system]) for tag, system in TAGS.items()}


def render_per_seed():
    """Every structure at every seed, as measured."""
    data = rows()
    out = ["| structure | seed | latest-wins | control | coexist | net | items |",
           "|---|---|---|---|---|---|---|"]
    for tag, label in LABELS.items():
        for seed in SEEDS:
            row = data[tag][seed]
            cells = [fixed(row[key], 3) for _, key in COLUMNS]
            out.append(f"| {label} | {seed} | " + " | ".join(cells)
                       + f" | {row['items']} |")
    return "\n".join(out)


def render_pooled():
    """The two seeds pooled, with each column's own interval and seed spread."""
    data, scores = rows(), pooled_scores()
    out = ["| structure | latest-wins | control | coexist | net | widest seed spread |",
           "|---|---|---|---|---|---|"]
    for tag in LABELS:
        cells = []
        for metric, probes in precision.PROBES.items():
            score = scores[tag][metric]
            cell = (f"{fixed(score, 3)} ±"
                    f"{fixed(precision.column_half_width(score, probes, len(SEEDS)), 3)}")
            if (tag, metric) == POOLED_EMPHASIS:
                cell = f"**{cell}**"
            cells.append(cell)
        cells.append(f"{fixed(precision.net(scores[tag]), 3)} ±"
                     f"{fixed(precision.half_width(scores[tag], seeds=len(SEEDS)), 3)}")
        spread = max(abs(data[tag][SEEDS[0]][m] - data[tag][SEEDS[1]][m])
                     for m in precision.PROBES)
        out.append(f"| {tag} | " + " | ".join(cells) + f" | {fixed(spread, 3)} |")
    return "\n".join(out)


def render_by_family():
    """Coexist preservation per family, pooled over both seeds."""
    data = rows()
    order = ["B14", "B17", "B3", "B9"]
    out = ["| family | " + " | ".join(order) + " | B14 over the best other |",
           "|---|---|---|---|---|---|"]
    for family in sorted(data["B14"][SEEDS[0]]["coexist_by_family"]):
        pooled = {tag: sum(data[tag][s]["coexist_by_family"][family]
                           for s in SEEDS) / len(SEEDS) for tag in order}
        lead = pooled["B14"] - max(pooled[t] for t in order[1:])
        out.append(f"| {family} | " + " | ".join(fixed(pooled[t], 3) for t in order)
                   + f" | +{fixed(lead, 3)} |")
    return "\n".join(out)


def render_anchor():
    """B3 on both datasets, which is what the dataset change did on its own."""
    round4 = {}
    for seed in SEEDS:
        with open(os.path.join(ROOT, "results_round4",
                               f"falsification_seed{seed}.json")) as f:
            for r in json.load(f)["rows"]:
                if r["system"] == TAGS["B3"]:
                    round4[seed] = r
    round5 = rows()["B3"]
    out = ["| column | round 4 (s7 / s11 / mean) | round 5 (s7 / s11 / mean) | move |",
           "|---|---|---|---|"]
    for label, key in COLUMNS:
        four = [round4[s][key] for s in SEEDS]
        five = [round5[s][key] for s in SEEDS]
        move = sum(five) / len(five) - sum(four) / len(four)
        # A minus sign, not a hyphen: the record sets every signed figure with
        # U+2212 and a re-render must not quietly replace it.
        sign = "−" if move < 0 else "+"
        out.append("| {} | {} | {} | {}{} |".format(
            label,
            " / ".join(fixed(v, 4) for v in four + [sum(four) / len(four)]),
            " / ".join(fixed(v, 4) for v in five + [sum(five) / len(five)]),
            sign, fixed(abs(move), 4)))
    return "\n".join(out)


TABLES = {
    "round5-per-seed": render_per_seed,
    "round5-pooled": render_pooled,
    "round5-by-family": render_by_family,
    "round5-anchor": render_anchor,
}


def replace(record, name, table):
    """Put one generated table between the markers that name it."""
    begin = record.find(BEGIN.format(name))
    if begin < 0:
        raise SystemExit(f"the record carries no generated block named {name}")
    end = record.find(END, begin)
    if end < 0:
        raise SystemExit(f"the {name} block has no end marker")
    return (record[:begin + len(BEGIN.format(name))] + "\n\n" + table + "\n\n"
            + record[end:])


def write():
    """Rewrite round 5's tables in the record from the committed results."""
    path = os.path.join(ROOT, "README.md")
    with open(path) as f:
        record = f.read()
    for name, render in TABLES.items():
        record = replace(record, name, render())
    with open(path, "w") as f:
        f.write(record)
    return path


if __name__ == "__main__":
    print(f"Rewrote round 5's tables in {write()} from the committed results")
