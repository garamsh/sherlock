"""Writes the record's results table from the committed run.

The record used to carry the table by hand and a register checked it against
`results_raw.json`. The table now comes from that file, so it cannot drift and
there is nothing to check: `system_runner.py --render` rewrites it between the
markers below and a run rewrites it too.

Everything outside the markers is the record's own prose and is left alone.
"""
from __future__ import annotations
import json
import os

BEGIN = "<!-- generated by the harness; do not edit between the markers -->"
END = "<!-- end generated -->"

# What the record calls each system, in the order it lists them, and the
# reading it emphasises. The figures come from the run; the wording and the
# emphasis are the record's and live here because the record cannot hold them
# and stay generated.
ROWS = [
    ("N1-voluntary-writeback", "N1 voluntary writeback", True, ""),
    ("N2-structured-writeback", "N2 structured writeback (80%)", True, ""),
    ("N2s-structured-lazy", "N2s structured, lazy model (50%)", False, ""),
    ("N3-platform-extraction", "N3 platform extraction", False, ""),
    ("N4-rolling-narrative", "N4 rolling narrative", False, ""),
    ("N5-log-ondemand", "N5 log + on-demand", False, ""),
    ("N6-forced-notes", "N6 forced notes", False, ""),
    ("N7-full-context", "N7 bounded context", False, " (grows, forgets old)"),
    ("N8-structured-coreblock", "N8 structured + core block", False, ""),
]


def render(rows):
    """The results table, from the rows `system_runner.py` computed."""
    by_system = {r["system"]: r for r in rows}
    out = ["| system | context-recall | store items | extra calls/turn | tokens/turn |",
           "|---|---|---|---|---|"]
    for system, label, emphasise, note in ROWS:
        r = by_system[system]
        recall = f"{r['context_recall']:.2f}"
        if emphasise:
            recall = f"**{recall}**"
        out.append("| {} | {} | {:.0f} | {:.2f} | {:.0f}{} |".format(
            label, recall, r["store_items"], r["extra_calls_per_turn"],
            r["injected_tokens_per_turn"], note))
    return "\n".join(out)


def replace(record, table):
    """Put the generated table between the record's markers."""
    begin, end = record.find(BEGIN), record.find(END)
    if begin < 0 or end < begin:
        raise SystemExit("the record does not carry both generated markers")
    return record[:begin + len(BEGIN)] + "\n\n" + table + "\n\n" + record[end:]


def write(root, rows=None):
    """Rewrite the record's table, from `rows` or from the committed run."""
    if rows is None:
        with open(os.path.join(root, "results_raw.json")) as f:
            rows = json.load(f)
    path = os.path.join(root, "README.md")
    with open(path) as f:
        record = f.read()
    with open(path, "w") as f:
        f.write(replace(record, render(rows)))
    return path
