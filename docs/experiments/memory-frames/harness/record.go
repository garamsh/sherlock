// The markers around the record's generated tables. Every figure the record
// carries sits between them and none is typed by hand: the project owner
// has ruled that a record restating result figures should generate them
// instead, so the prose outside these markers carries no number and the
// harness writes the tables from the committed results.
const (
	beginMarker = "<!-- generated by the harness; do not edit between the markers -->"
	endMarker   = "<!-- end generated -->"
)

// notApplicable is what a cell holds where the figure does not exist — a
// class not yet planted at that year, or a year with no superseded value to
// return.
const notApplicable = "n/a"

// renderRecord rewrites the record's generated block from a committed
// result file.
func renderRecord(resultPath, recordPath string) error {
	body, err := os.ReadFile(resultPath)
	if err != nil {
		return fmt.Errorf("read %s: %w", resultPath, err)
	}
	var result Run
	if err := json.Unmarshal(body, &result); err != nil {
		return fmt.Errorf("decode %s: %w", resultPath, err)
	}
	record, err := os.ReadFile(recordPath)
	if err != nil {
		return fmt.Errorf("read %s: %w", recordPath, err)
	}
	rewritten, err := Replace(string(record), RenderTables(result))
	if err != nil {
		return fmt.Errorf("%s: %w", recordPath, err)
	}
	if err := os.WriteFile(recordPath, []byte(rewritten), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", recordPath, err)
	}
	return nil
}

// Replace puts the generated tables between the record's markers, leaving
// everything outside them alone.
func Replace(record, tables string) (string, error) {
	begin := strings.Index(record, beginMarker)
	end := strings.Index(record, endMarker)
	if begin < 0 || end < 0 || end < begin {
		return "", fmt.Errorf("the record does not carry both generated markers")
	}
	return record[:begin+len(beginMarker)] + "\n\n" + tables + "\n" + record[end:], nil
}

// RenderTables is every figure the record publishes.
func RenderTables(r Run) string {
	var b strings.Builder
	renderRun(&b, r)
	renderYears(&b, r)
	renderSizes(&b, r)
	renderArity(&b, r)
	renderReach(&b, r)
	renderCapacity(&b, r)
	renderCoupling(&b, r)
	renderSweep(&b, r)
	renderHealing(&b, r)
	renderDeclarer(&b, r)
	renderModelRun(&b, r)
	renderBias(&b, r)
	renderStability(&b, r)
	renderDisagreement(&b, r)
	renderCost(&b, r)
	renderPaid(&b, r)
	return strings.TrimRight(b.String(), "\n")
}

