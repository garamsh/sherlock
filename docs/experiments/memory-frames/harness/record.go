// renderComparison is the page this record exists to put in front of a
// reader: every structure as a row, with what it holds and how it decides
// beside what that scores and what it costs. It carries no heading of its
// own because the record's section heading stands directly above it — a
// reader arriving at the comparison should meet the table and not another
// heading.
//
// The figures are the last year of the decade run in the arm that extracts
// perfectly, which is the one year and the one arm every structure can be
// read on: in the other arm the addressed structures hold nothing, and that
// is a finding the section states rather than a column.
func renderComparison(b *strings.Builder, r Run) {
	fmt.Fprintf(b, "| structure | what it holds | how it decides | recall | %s | stale returned | context chars | units read | stored KB |\n",
		strings.Join(classNames, " | "))
	fmt.Fprintf(b, "|---|---|---|---|%s---|---|---|---|\n", strings.Repeat("---|", len(classNames)))
	for _, name := range frameNames {
		for _, f := range r.Frames {
			if f.Frame != name || f.Arm != armOracle || len(f.Years) == 0 || len(f.Sizes) == 0 {
				continue
			}
			y := f.Years[len(f.Years)-1]
			size := f.Sizes[len(f.Sizes)-1].Size
			fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s | %s | %s | %s | %.1f |\n",
				f.Frame, frameHolds[f.Frame], frameDecides[f.Frame], figure(y.Recall),
				strings.Join(classCells(y), " | "), figure(y.Stale),
				figureAt(y.ContextChars, 0), figureAt(y.Scanned, 1), kilobytes(size.StoredBytes))
		}
	}
	fmt.Fprintln(b)
}

