// figure renders a number with the interval its sample supports. A figure
// without one is unreadable: it cannot be told from a figure the workload
// only appeared to produce.
func figure(f Figure) string { return figureAt(f, 3) }

// figureAt renders a figure to the given number of decimals. A count of
// characters is not read to a thousandth; a proportion is.
func figureAt(f Figure, decimals int) string {
	if f.N == 0 {
		return notApplicable
	}
	return fmt.Sprintf("%.*f ±%.*f", decimals, f.Mean, decimals, f.Half)
}

// kilobytes divides by 1,024 once. Five committed result files once
// reported a quantity divided by it twice (#432), so the conversion has one
// site.
func kilobytes(bytes int64) float64 {
	return float64(bytes) / 1024
}
