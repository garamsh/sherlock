// renderYears is the per-year, per-class table: the figure this record
// exists to carry.
func renderYears(b *strings.Builder, r Run) {
	fmt.Fprintf(b, "### What each frame answered, by year\n\n")
	fmt.Fprintf(b, "| frame | arm | year | asked | recall | %s | stale returned | context chars | units read |\n",
		strings.Join(classNames, " | "))
	fmt.Fprintf(b, "|---|---|---|---|---|%s---|---|---|\n", strings.Repeat("---|", len(classNames)))
	for _, f := range r.Frames {
		for _, y := range f.Years {
			byClass := map[string]ClassResult{}
			for _, c := range y.Classes {
				byClass[c.Class] = c
			}
			cells := make([]string, 0, len(classNames))
			for _, class := range classNames {
				c, ok := byClass[class]
				if !ok {
					cells = append(cells, notApplicable)
					continue
				}
				cells = append(cells, figure(c.Recall))
			}
			fmt.Fprintf(b, "| `%s` | `%s` | %d | %d | %s | %s | %s | %s | %s |\n",
				f.Frame, f.Arm, y.Year, y.Probes, figure(y.Recall), strings.Join(cells, " | "),
				figure(y.Stale), figureAt(y.ContextChars, 0), figureAt(y.Scanned, 1))
		}
	}
	fmt.Fprintln(b)
}

// renderSizes is what each frame held at the first, middle and last year.
func renderSizes(b *strings.Builder, r Run) {
	fmt.Fprintf(b, "### What each frame held\n\n")
	fmt.Fprintf(b, "| frame | arm | year | units | content KB | stored KB |\n|---|---|---|---|---|---|\n")
	for _, f := range r.Frames {
		for _, s := range f.Sizes {
			fmt.Fprintf(b, "| `%s` | `%s` | %d | %d | %.1f | %.1f |\n",
				f.Frame, f.Arm, s.Year, s.Size.Units, kilobytes(s.Size.ContentBytes), kilobytes(s.Size.StoredBytes))
		}
	}
	fmt.Fprintln(b)
}

// renderArity is what an attribute-addressed frame has to decide arity
// from: the interval between the writes to one address, and how the other
// addresses under an attribute have behaved.
func renderArity(b *strings.Builder, r Run) {
	fmt.Fprintf(b, "### What the addresses look like\n\n")
	fmt.Fprintf(b, "| class | addresses | values per address | years between the last two writes |\n")
	fmt.Fprintf(b, "|---|---|---|---|\n")
	for _, c := range r.Arity.Classes {
		fmt.Fprintf(b, "| `%s` | %d | %s | %s |\n", c.Class, c.Addresses,
			figure(c.Values), figureAt(c.Gap, 2))
	}
	fmt.Fprintln(b)

	fmt.Fprintf(b, "| attribute | addresses | written more than one value | share |\n|---|---|---|---|\n")
	for _, a := range r.Arity.Attributes {
		fmt.Fprintf(b, "| `%s` | %d | %d | %.3f |\n", a.Attribute, a.Addresses, a.MultiValued, a.Share)
	}
	fmt.Fprintln(b)
}

// renderSweep is what a wrong declaration costs, per direction and never
