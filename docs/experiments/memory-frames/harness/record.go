// The markers around the record's generated tables. Every figure the record
// carries sits between them and none is typed by hand: the project owner
// has ruled that a record restating result figures should generate them
// instead, so the prose outside these markers carries no number and the
// harness writes the tables from the committed results.
//
// A region is named, because the record's tables sit beside the prose they
// are evidence for rather than in one block at the end. The name in the
// record's marker is the name the renderer gives the tables that fill it,
// and a name on one side with nothing on the other is an error rather than
// a table quietly dropped.
const (
	beginPrefix = "<!-- generated by the harness: "
	beginSuffix = "; do not edit between the markers -->"
	endMarker   = "<!-- end generated -->"
)

// The names of the record's generated regions. Each is the evidence one
// section of the record rests on.
const (
	regionComparison  = "comparison"
	regionWorkload    = "workload"
	regionDecade      = "decade"
	regionArity       = "arity"
	regionAddress     = "address"
	regionProse       = "prose"
	regionDeclaration = "declaration"
	regionDestroy     = "destroy"
	regionReach       = "reach"
	regionConstraint  = "constraint"
	regionLanguage    = "language"
	regionFinding     = "finding"
	regionLiterature  = "literature"
	regionCost        = "cost"
)

// Section is one named region of generated tables: the name the record's
// markers carry, and what fills it.
type Section struct {
	Name   string
	Tables string
}

// notApplicable is what a cell holds where the figure does not exist — a
// class not yet planted at that year, or a year with no superseded value to
// return.
const notApplicable = "n/a"

// renderRecord rewrites the record's generated block from the committed
// result files.
func renderRecord(files runFiles) error {
	body, err := os.ReadFile(files.decade)
	if err != nil {
		return fmt.Errorf("read %s: %w", files.decade, err)
	}
	var result Run
	if err := json.Unmarshal(body, &result); err != nil {
		return fmt.Errorf("decode %s: %w", files.decade, err)
	}
	if err := readStudy(files.constrained, &result.Constrained); err != nil {
		return err
	}
	if err := readStudy(files.shapes, &result.Shapes); err != nil {
		return err
	}
	var finding FindingStudy
	if err := readStudy(files.finding, &finding); err != nil {
		return err
	}
	result.Prose, err = readCommittedProse(files.prose)
	if err != nil {
		return err
	}
	result.ProseBefore, err = readCommittedProse(files.proseBefore)
	if err != nil {
		return err
	}
	result.Addresser, err = readCommittedAddresses(files.addresses)
	if err != nil {
		return err
	}
	if len(finding.Frames) > 0 {
		result.Finding = &finding
	}
	record, err := os.ReadFile(files.record)
	if err != nil {
		return fmt.Errorf("read %s: %w", files.record, err)
	}
	rewritten, err := Replace(string(record), RenderTables(result))
	if err != nil {
		return fmt.Errorf("%s: %w", files.record, err)
	}
	if err := os.WriteFile(files.record, []byte(rewritten), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", files.record, err)
	}
	return nil
}

// readStudy reads one study's committed file into the run. A study that has
// not been run has no file, and the tables it feeds are left out rather
// than rendered empty.
func readStudy(path string, into any) error {
	body, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}
	if err := json.Unmarshal(body, into); err != nil {
		return fmt.Errorf("decode %s: %w", path, err)
	}
	return nil
}

// Replace puts each section's tables between the markers of the region that
// names it, leaving everything outside the markers alone.
func Replace(record string, sections []Section) (string, error) {
	placed := map[string]bool{}
	var b strings.Builder
	rest := record
	for {
		begin := strings.Index(rest, beginPrefix)
		if begin < 0 {
			break
		}
		opened := rest[begin+len(beginPrefix):]
		named := strings.Index(opened, beginSuffix)
		if named < 0 {
			return "", fmt.Errorf("a generated region opens without naming what fills it")
		}
		name := opened[:named]
		body, ok := lookup(sections, name)
		if !ok {
			return "", fmt.Errorf("the record has a generated region %q the harness does not render", name)
		}
		closed := opened[named+len(beginSuffix):]
		end := strings.Index(closed, endMarker)
		if end < 0 {
			return "", fmt.Errorf("the generated region %q does not close", name)
		}
		b.WriteString(rest[:begin+len(beginPrefix)+named+len(beginSuffix)])
		b.WriteString("\n\n" + body + "\n")
		placed[name] = true
		rest = closed[end:]
	}
	for _, s := range sections {
		if !placed[s.Name] {
			return "", fmt.Errorf("the harness renders %q and the record has nowhere to put it", s.Name)
		}
	}
	b.WriteString(rest)
	return b.String(), nil
}

// lookup finds a section by the name a marker gave it.
func lookup(sections []Section, name string) (string, bool) {
	for _, s := range sections {
		if s.Name == name {
			return s.Tables, true
		}
	}
	return "", false
}

// RenderTables is every figure the record publishes, grouped into the
// regions the record carries and in the order the record carries them.
func RenderTables(r Run) []Section {
	return []Section{
		section(regionComparison, r, renderComparison),
		section(regionWorkload, r, renderRun),
		section(regionDecade, r, renderYears, renderSizes),
		section(regionArity, r, renderArity),
		section(regionAddress, r, renderQuestions, renderAddresser),
		section(regionProse, r, renderProse),
		section(regionDeclaration, r, renderSweep, renderHealing, renderDeclarer, renderModelRun),
		section(regionDestroy, r, renderBias, renderStability, renderDisagreement),
		section(regionReach, r, renderReach, renderCoupling, renderCapacity),
		section(regionConstraint, r, renderBounds, renderRules, renderBudgets),
		section(regionLanguage, r, renderLanguage, renderExtraction, renderShapes),
		section(regionFinding, r, renderFinding),
		section(regionLiterature, r, renderIdentity),
		section(regionCost, r, renderCost, renderPaid),
	}
}

// section renders one region's tables in the order they are given.
func section(name string, r Run, renderers ...func(*strings.Builder, Run)) Section {
	var b strings.Builder
	for _, render := range renderers {
		render(&b, r)
	}
	return Section{Name: name, Tables: strings.TrimRight(b.String(), "\n")}
}

