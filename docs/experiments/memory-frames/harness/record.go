// renderPaid is the money. It is a table of its own, after every free
// figure and never mixed into one, so no reader has to work out which
// numbers cost something.
func renderPaid(b *strings.Builder, r Run) {
	fmt.Fprintf(b, "### What the paid half cost\n\n")
	var rows [][2]any
	var total float64
	if d := r.Declarer; d != nil {
		total += d.CostUSD
		rows = append(rows,
			[2]any{"model", d.Model},
			[2]any{"paid calls, declaring", d.Calls},
			[2]any{"assertions declared", d.Asked},
			[2]any{"prompt tokens", d.PromptTokens},
			[2]any{"completion tokens", d.CompletionTokens},
			[2]any{"price per million prompt tokens, USD", d.PriceInPerM},
			[2]any{"price per million completion tokens, USD", d.PriceOutPerM},
			[2]any{"price read on", d.PriceRead},
			[2]any{"cost of declaring, USD", fmt.Sprintf("%.4f", d.CostUSD)},
			[2]any{"call bound declaring refuses to pass", declareCallLimit},
			[2]any{"cost bound declaring refuses to pass, USD", fmt.Sprintf("%.2f", declareCostLimit)})
	}
	if a := r.Addresser; a != nil {
		total += a.CostUSD
		rows = append(rows,
			[2]any{"paid calls, addressing", a.Calls},
			[2]any{"assertions addressed", a.Asked},
			[2]any{"prompt tokens, addressing", a.PromptTokens},
			[2]any{"completion tokens, addressing", a.CompletionTokens},
			[2]any{"cost of addressing, USD", fmt.Sprintf("%.4f", a.CostUSD)},
			[2]any{"call bound addressing refuses to pass", addressCallLimit},
			[2]any{"cost bound addressing refuses to pass, USD", fmt.Sprintf("%.2f", addressCostLimit)})
	}
	if p := r.Prose; p != nil {
		total += p.CostUSD
		rows = append(rows,
			[2]any{"model, the shipped prose round", p.Model},
			[2]any{"paid calls, the shipped prose round", p.Calls},
			[2]any{"assertions put through the shipped prose", p.Asked},
			[2]any{"probes put through the read step", p.Reads},
			[2]any{"prompt tokens, the shipped prose round", p.PromptTokens},
			[2]any{"completion tokens, the shipped prose round", p.CompletionTokens},
			[2]any{"price per million prompt tokens, the shipped prose round, USD", p.PriceInPerM},
			[2]any{"price per million completion tokens, the shipped prose round, USD", p.PriceOutPerM},
			[2]any{"price read on, the shipped prose round", p.PriceRead},
			[2]any{"cost of the shipped prose round, USD", fmt.Sprintf("%.4f", p.CostUSD)},
			[2]any{"call bound the shipped prose round refuses to pass", proseCallLimit},
			[2]any{"cost bound the shipped prose round refuses to pass, USD", fmt.Sprintf("%.2f", proseCostLimit)})
	}
	if s := r.Stability; s != nil {
		total += s.CostUSD
		rows = append(rows,
			[2]any{"paid calls, resampling", s.Calls},
			[2]any{"prompt tokens, resampling", s.PromptTokens},
			[2]any{"completion tokens, resampling", s.CompletionTokens},
			[2]any{"cost of resampling, USD", fmt.Sprintf("%.4f", s.CostUSD)},
			[2]any{"call bound resampling refuses to pass", resampleCallLimit},
			[2]any{"cost bound resampling refuses to pass, USD", fmt.Sprintf("%.2f", resampleCostLimit)})
	}
	var extracted []*ExtractionScore
	var reading float64
	for _, s := range r.Shapes {
		if s.Extraction == nil {
			continue
		}
		extracted = append(extracted, s.Extraction)
		reading += s.Extraction.CostUSD
	}
	if len(extracted) > 0 {
		total += reading
		rows = append(rows,
			[2]any{"cost of reading the messages, USD", fmt.Sprintf("%.4f", reading)},
			[2]any{"call bound reading refuses to pass", extractCallLimit},
			[2]any{"cost bound reading refuses to pass, USD", fmt.Sprintf("%.2f", extractCostLimit)})
	}
	if r.Finding != nil && r.Finding.Resolution != nil {
		q := r.Finding.Resolution
		total += q.CostUSD
		rows = append(rows,
			[2]any{"paid calls, resolving", q.Calls},
			[2]any{"questions resolved", q.Asked},
			[2]any{"prompt tokens, resolving", q.PromptTokens},
			[2]any{"completion tokens, resolving", q.CompletionTokens},
			[2]any{"cost of resolving, USD", fmt.Sprintf("%.4f", q.CostUSD)},
			[2]any{"call bound resolving refuses to pass", resolveCallLimit},
			[2]any{"cost bound resolving refuses to pass, USD", fmt.Sprintf("%.2f", resolveCostLimit)})
	}
	if len(rows) == 0 {
		fmt.Fprintf(b, "| quantity | value |\n|---|---|\n| paid calls | 0 |\n")
		fmt.Fprintln(b)
		return
	}
	rows = append(rows, [2]any{"cost of this record in total, USD", fmt.Sprintf("%.4f", total)})
	fmt.Fprintf(b, "| quantity | value |\n|---|---|\n")
	for _, row := range rows {
		fmt.Fprintf(b, "| %s | %v |\n", row[0], row[1])
	}
	fmt.Fprintln(b)

	if len(extracted) == 0 {
		return
	}
	// A shape pays for the messages it did not already have an answer for,
	// so its calls are below its messages wherever a message repeats
	// between shapes. The count is what was bought, not what was read.
	fmt.Fprintf(b, "| shape | messages read | paid calls | tokens | cost USD |\n")
	fmt.Fprintf(b, "|---|---|---|---|---|\n")
	for _, e := range extracted {
		fmt.Fprintf(b, "| `%s` | %d | %d | %d | %.4f |\n",
			e.Shape, e.Messages, e.Calls, e.Tokens, e.CostUSD)
	}
	fmt.Fprintln(b)
}

