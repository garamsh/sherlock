// The record's three result tables are written from the committed result
// files rather than typed. Each sits between a pair of markers naming it, so
// a cell cannot disagree with the run behind it and there is nothing left to
// check. The -render flag rewrites them and measures nothing; a measuring run
// rewrites them too, from every committed file and not only the one it just
// wrote.
//
// The prose outside the markers still states figures, and
// claim_sources_test.go still reads those against their sources.
const (
	beginMarker = "<!-- generated by the harness; do not edit between the markers: %s -->"
	endMarker   = "<!-- end generated -->"
)

// The generated tables, by the name their markers carry.
const (
	blockScores     = "scores"
	blockFamilies   = "separability-families"
	blockThresholds = "separability-thresholds"
)

// separabilityEmbedders are the embedders the separability tables report, in
// the order the record lists them. It is measuredEmbedders plus the cache
// replay, which answers this question and not the retrieval one.
var separabilityEmbedders = []string{embedderHashing, embedderOpenAI, embedderOpenAI512}

// renderRecord rewrites the record's tables from the committed results.
func renderRecord(out, recordPath string) error {
	runs := map[string]Run{}
	for _, name := range measuredEmbedders {
		var run Run
		if err := readJSON(filepath.Join(out, fmt.Sprintf("retrieval_seed%d_%s.json", recordSeed, name)), &run); err != nil {
			return err
		}
		runs[name] = run
	}
	seps := map[string]Separability{}
	for _, name := range separabilityEmbedders {
		var sep Separability
		if err := readJSON(filepath.Join(out, fmt.Sprintf("separability_seed%d_%s.json", recordSeed, name)), &sep); err != nil {
			return err
		}
		seps[name] = sep
	}
	body, err := os.ReadFile(recordPath)
	if err != nil {
		return fmt.Errorf("read %s: %w", recordPath, err)
	}
	record := string(body)
	for name, table := range map[string]string{
		blockScores:     RenderScores(runs),
		blockFamilies:   RenderFamilies(seps),
		blockThresholds: RenderThresholds(seps),
	} {
		if record, err = Replace(record, name, table); err != nil {
			return fmt.Errorf("%s: %w", recordPath, err)
		}
	}
	if err := os.WriteFile(recordPath, []byte(record), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", recordPath, err)
	}
	return nil
}

// recordSeed is the seed the committed results and therefore the record are
// at. A run at another seed writes its own files and does not rewrite this
// record, which states seed 7 throughout.
const recordSeed = 7

// Replace puts one generated table between the markers that name it.
func Replace(record, name, table string) (string, error) {
	begin := fmt.Sprintf(beginMarker, name)
	start := strings.Index(record, begin)
	if start < 0 {
		return "", fmt.Errorf("the record carries no generated block named %q", name)
	}
	end := strings.Index(record[start:], endMarker)
	if end < 0 {
		return "", fmt.Errorf("the %q block has no end marker", name)
	}
	return record[:start+len(begin)] + "\n\n" + table + "\n\n" + record[start+end:], nil
}

// RenderScores is what the read path scores, every embedder, planting and
// store size the runs hold.
func RenderScores(runs map[string]Run) string {
	var b strings.Builder
	fmt.Fprintf(&b, "| embedder | planting | store | recall@1 | precision@1 | recall@5 | precision@5 "+
		"| recall@10 | precision@10 | recall@budget | precision@budget | returned@budget | best rank |\n")
	fmt.Fprintf(&b, "|%s\n", strings.Repeat("---|", 13))
	for _, name := range measuredEmbedders {
		run := runs[name]
		for _, arm := range run.Arms {
			for _, size := range arm.Sizes {
				f := size.Figures
				fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
					run.Embedder, arm.Name, thousands(size.Size),
					figure(f.RecallAt1), figure(f.PrecisionAt1),
					figure(f.RecallAt5), figure(f.PrecisionAt5),
					figure(f.RecallAtLimit), figure(f.PrecisionAtLimit),
					figure(f.RecallAtBudget), figure(f.PrecisionAtBudget),
					count(f.ReturnedAtBudget), count(f.BestRank))
			}
		}
	}
	return strings.TrimRight(b.String(), "\n")
}

// RenderFamilies is each pair family's cosine distribution and what the
// store did with it when these results were measured, under every
// embedder measured. The store retires nothing now (#529), so a re-run
// reports 0 in the retired column; the committed figures are what the
// mechanism did while it existed.
func RenderFamilies(seps map[string]Separability) string {
	var b strings.Builder
	fmt.Fprintf(&b, "| embedder | family | must supersede? | min | median | max | IQR "+
		"| retired by the store as it then ran |\n")
	fmt.Fprintf(&b, "|%s\n", strings.Repeat("---|", 8))
	for _, name := range separabilityEmbedders {
		s := seps[name]
		for _, family := range familyOrder {
			f := familyIn(s, family)
			fmt.Fprintf(&b, "| `%s` %d | %s | %s | %s | %s | %s | %s | %d of %d |\n",
				s.Embedder, s.Dimensions, f.Name, yesNo(f.MustSupersede),
				fixed(f.Min, 3), fixed(f.Median, 3), fixed(f.Max, 3), fixed(f.IQR, 3),
				f.Superseded, f.Pairs)
		}
	}
	return strings.TrimRight(b.String(), "\n")
}

// RenderThresholds is what each embedder does with the thresholds the
// project has used, and with the best one available to it.
func RenderThresholds(seps map[string]Separability) string {
	var b strings.Builder
	fmt.Fprintf(&b, "| embedder | at %s, the value then shipped | at %s, ADR 0006's value then "+
		"| best possible threshold | coexist scores at or above a correction |\n",
		fixed(seps[embedderHashing].ShippedThreshold.Threshold, 2),
		fixed(seps[embedderHashing].ADRThreshold.Threshold, 2))
	fmt.Fprintf(&b, "|%s\n", strings.Repeat("---|", 5))
	for _, name := range separabilityEmbedders {
		s := seps[name]
		fmt.Fprintf(&b, "| `%s` %d | %d correct, %d wrong | %d correct, %d wrong "+
			"| %s, accuracy %s | %s of cross pairs |\n",
			s.Embedder, s.Dimensions,
			s.ShippedThreshold.CorrectRetirements, s.ShippedThreshold.WrongRetirements,
			s.ADRThreshold.CorrectRetirements, s.ADRThreshold.WrongRetirements,
			fixed(s.BestThreshold.Threshold, 2), fixed(s.BestThreshold.Accuracy, 3),
			fixed(s.Overlap.CoexistAtOrAboveCorrect, 3))
	}
	return strings.TrimRight(b.String(), "\n")
}

// familyIn is one named family of a separability result.
func familyIn(s Separability, name string) FamilyScores {
	for _, f := range s.Families {
		if f.Name == name {
			return f
		}
	}
	return FamilyScores{Name: name}
}

// figure renders a proportion with the interval its sample supports. A
// figure without one cannot be told from one the corpus only appeared to
// produce.
func figure(f Figure) string { return fixed(f.Mean, 3) + " ±" + fixed(f.Half, 3) }

// count renders a figure that counts rather than proportions: a rank, or
// how many memories a budget returned.
func count(f Figure) string { return fixed(f.Mean, 1) + " ±" + fixed(f.Half, 1) }

// fixed prints a value to the given decimals, rounding half away from zero.
// Go's own formatting rounds half to even, which prints 0.4925 as 0.492 and
// 67.35 as 67.3 — the record rounds a half up and every committed figure in
// it was written that way, so the renderer has to as well.
func fixed(value float64, places int) string {
	return strconv.FormatFloat(halfUp(value, places), 'f', places, 64)
}

// halfUp rounds away from zero, the direction a reader assumes.
func halfUp(value float64, places int) float64 {
	factor := math.Pow(10, float64(places))
	rounded := math.Floor(math.Abs(value)*factor+0.5) / factor
	if value < 0 {
		return -rounded
	}
	return rounded
}

// thousands groups a store size the way the record prints it.
func thousands(n int) string {
	body := fmt.Sprintf("%d", n)
	var out []byte
	for i, c := range []byte(body) {
		if i > 0 && (len(body)-i)%3 == 0 {
			out = append(out, ',')
		}
		out = append(out, c)
	}
	return string(out)
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

func readJSON(path string, into any) error {
	body, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}
	if err := json.Unmarshal(body, into); err != nil {
		return fmt.Errorf("decode %s: %w", path, err)
	}
	return nil
}
